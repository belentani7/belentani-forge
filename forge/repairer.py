class Outcome(str, Enum):
    FIXED = "FIXED"
    WOULD_FIX = "WOULD_FIX"
    ALREADY_OK = "ALREADY_OK"
    SKIPPED_FROZEN = "SKIPPED_FROZEN"
    NEEDS_DECISION = "NEEDS_DECISION"
    FAILED = "FAILED"


@dataclass
class Repair:
    project: str
    fix: str
    outcome: str
    detail: str = ""
    path: str = ""

    def to_dict(self) -> dict:
        return asdict(self)


@dataclass
class Fix:
    """One idempotent repair: a target file and how to render it."""
    name: str
    filename: str
    render: Callable[[Project], str]
    applies_when: Callable[[Project], bool]

    def target(self, root: Path) -> Path:
        return root / self.filename


def _license(project: Project) -> str:
    return render(LICENSE_MIT, YEAR=datetime.now().year, AUTHOR=AUTHOR)


def _readme(project: Project) -> str:
    stack = project.stack or "unspecified"
    return (
        "# %s\n\n"
        "%s\n\n"
        "## Stack\n\n`%s`\n\n"
        "## Status\n\n"
        "Scaffolded by FORGE. Replace this file with a real description:\n"
        "what it does, how to run it, and what it depends on.\n"
        % (project.name,
           "_No description yet._",
           stack)
    )


FIXES: List[Fix] = [
    Fix("gitignore", ".gitignore",
        lambda p: GITIGNORE_COMMON,
        lambda p: not p.has_gitignore),
    Fix("license", "LICENSE",
        _license,
        lambda p: not p.has_license),
    Fix("env_example", ".env.example",
        lambda p: ENV_EXAMPLE,
        lambda p: not p.has_env_example),
    Fix("readme", "README.md",
        _readme,
        lambda p: not p.has_readme),
    Fix("ci", ".github/workflows/ci.yml",
        lambda p: CI_GENERIC,
        lambda p: not p.has_ci and p.stack.startswith("python")),
    Fix("smoke_test", "tests/test_smoke.py",
        lambda p: SMOKE_TEST_PY,
        lambda p: not p.has_tests and p.stack.startswith("python")),
]

# Issues that must not be auto-resolved.
MANUAL_ONLY = {
    "No git remote configured":
        "needs the target GitHub repo — guessing could push to the wrong place",
    "Dirty git state":
        "uncommitted work belongs to you; committing it silently is not safe",
    "Very dirty git state":
        "uncommitted work belongs to you; committing it silently is not safe",
}


def needs_decision(project: Project) -> List[Repair]:
    """Report issues that a machine must not resolve on its own."""
    out = []
    for issue in project.issues:
        text = issue.split(": ", 1)[-1]
        for marker, why in MANUAL_ONLY.items():
            if text.startswith(marker):
                out.append(Repair(project.name, marker, Outcome.NEEDS_DECISION.value,
                                  why, project.path))
                break
    return out


def repair_project(project: Project, apply: bool = False,
                   fixes: Optional[List[Fix]] = None) -> List[Repair]:
    """Apply every applicable fix to one project.

    Returns one :class:`Repair` per fix considered, so a caller can see what
    was skipped as well as what changed.
    """
    results: List[Repair] = []

    if project.frozen or is_frozen_project(project.name):
        return [Repair(project.name, "all", Outcome.SKIPPED_FROZEN.value,
                       "frozen this phase — documented, not modified", project.path)]

    if project.archived:
        return [Repair(project.name, "all", Outcome.SKIPPED_FROZEN.value,
                       "archived upstream — read-only, a diff here can never land",
                       project.path)]

    if project.classification == "BACKUP":
        return [Repair(project.name, "all", Outcome.SKIPPED_FROZEN.value,
                       "classified BACKUP — preserved as-is", project.path)]

    root = Path(project.path) if project.path else None
    if root is None or not root.is_dir():
        return [Repair(project.name, "all", Outcome.FAILED.value,
                       "local path not found", project.path)]

    for fix in (fixes or FIXES):
        if not fix.applies_when(project):
            results.append(Repair(project.name, fix.name, Outcome.ALREADY_OK.value))
            continue

        target = fix.target(root)
        if target.exists():
            results.append(Repair(project.name, fix.name, Outcome.ALREADY_OK.value,
                                  "already present", str(target)))
            continue

        try:
            guard_write(target, project_name=project.name)
        except SafetyViolation as exc:
            results.append(Repair(project.name, fix.name, Outcome.SKIPPED_FROZEN.value,
                                  str(exc), str(target)))
            continue

        if not apply:
            results.append(Repair(project.name, fix.name, Outcome.WOULD_FIX.value,
                                  "would create", str(target)))
            continue

        try:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(fix.render(project), encoding="utf-8")
            results.append(Repair(project.name, fix.name, Outcome.FIXED.value,
                                  "created", str(target)))
        except OSError as exc:
            results.append(Repair(project.name, fix.name, Outcome.FAILED.value,
                                  str(exc), str(target)))

    results.extend(needs_decision(project))
    return results


def repair_all(projects: List[Project], apply: bool = False,
               limit: Optional[int] = None) -> List[Repair]:
    targets = projects[:limit] if limit else projects
    out: List[Repair] = []
    for project in targets:
        out.extend(repair_project(project, apply=apply))
    return out


def summarise(repairs: List[Repair]) -> Dict[str, int]:
    counts: Dict[str, int] = {}
    for r in repairs:
        counts[r.outcome] = counts.get(r.outcome, 0) + 1
    return counts


def actionable(repairs: List[Repair]) -> List[Repair]:
    """Only the entries that represent real work done or pending."""
    return [r for r in repairs
            if r.outcome in (Outcome.FIXED.value, Outcome.WOULD_FIX.value,
                             Outcome.NEEDS_DECISION.value, Outcome.FAILED.value)]

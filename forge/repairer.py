"""Repairer — closes the gaps FORGE diagnoses, without touching what matters.

Three rules make this safe to point at 48 repositories at once:

  * **Create only.** A fix never overwrites an existing file. Running the
    repairer twice changes nothing the second time.
  * **Frozen work is untouchable.** Frozen projects and visual assets are
    skipped before a path is ever opened.
  * **Dry run by default.** Nothing is written without ``apply=True``.

Repairs that need a human decision — configuring a git remote, resolving
uncommitted work — are reported as :attr:`Outcome.NEEDS_DECISION`, never
guessed at.
"""
from __future__ import annotations

from dataclasses import dataclass, field, asdict
from datetime import datetime
from enum import Enum
from pathlib import Path
from typing import Callable, Dict, List, Optional

from . import config
from .engine import AUTHOR, ENV_EXAMPLE, GITIGNORE_COMMON, LICENSE_MIT, render
from .models import Project
from .safety import SafetyViolation, guard_write, is_frozen_project

